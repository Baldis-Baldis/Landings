-- MyLandings core schema. Access rules are in the next migration; nothing here is reachable yet.
-- An airfield is either a catalogue code (static files in the repo) or the user's own custom strip.
-- Catalogue codes have no FK on purpose: the catalogue is not in the database.

create schema if not exists private;
revoke all on schema private from public;

-- ---------- users ----------

-- Everything in this table is visible to everyone. Never add anything private here.
-- Created by the client when the user picks a nickname, not by a trigger on auth.users:
-- a failing trigger there would block all sign-ups.
create table public.profiles (
  id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  display_name text not null check (
    char_length(display_name) between 3 and 30
    and display_name = btrim(display_name)
    and display_name !~ '[[:cntrl:]]'
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index profiles_display_name_key on public.profiles (lower(display_name));

create table public.user_settings (
  user_id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  terms_version text check (char_length(terms_version) <= 32),
  terms_accepted_at timestamptz,
  lang text check (lang in ('cs', 'en')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Managed only from the SQL editor. No client ever gets a grant on this table.
create table public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

-- ---------- personal records ----------

create table public.custom_airfields (
  id uuid primary key default gen_random_uuid(), -- generated by the client, so strips can be created offline
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 100),
  short text check (char_length(short) <= 8),
  description text check (char_length(description) <= 2000),
  lat double precision not null check (lat between -90 and 90),
  lon double precision not null check (lon between -180 and 180),
  elev text check (char_length(elev) <= 8),
  town text check (char_length(town) <= 100),
  client_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, user_id) -- target of the composite FKs: a record can point only to the owner's own strip
);
create index custom_airfields_user_id_idx on public.custom_airfields (user_id);

create table public.landings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  airfield_code text check (airfield_code ~ '^[A-Z0-9-]{3,12}$'),
  custom_airfield_id uuid,
  landed_on date, -- the app allows a landing with the date cleared
  client_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (num_nonnulls(airfield_code, custom_airfield_id) = 1),
  foreign key (custom_airfield_id, user_id) references public.custom_airfields (id, user_id) on delete cascade,
  unique nulls not distinct (user_id, airfield_code, custom_airfield_id)
);
create index landings_custom_airfield_idx on public.landings (custom_airfield_id, user_id);

create table public.airfield_flags (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  airfield_code text check (airfield_code ~ '^[A-Z0-9-]{3,12}$'),
  custom_airfield_id uuid,
  is_favorite boolean not null default false,
  wants_visit boolean not null default false,
  client_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (num_nonnulls(airfield_code, custom_airfield_id) = 1),
  foreign key (custom_airfield_id, user_id) references public.custom_airfields (id, user_id) on delete cascade,
  unique nulls not distinct (user_id, airfield_code, custom_airfield_id)
);
create index airfield_flags_custom_airfield_idx on public.airfield_flags (custom_airfield_id, user_id);

-- ---------- content that can be shared ----------

create table public.comments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  airfield_code text check (airfield_code ~ '^[A-Z0-9-]{3,12}$'),
  custom_airfield_id uuid,
  body text not null check (char_length(body) between 1 and 2000),
  is_public boolean not null default false,
  moderation text not null default 'visible' check (moderation in ('visible', 'hidden')),
  client_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (num_nonnulls(airfield_code, custom_airfield_id) = 1),
  check (custom_airfield_id is null or not is_public), -- a public item would reveal a private strip
  foreign key (custom_airfield_id, user_id) references public.custom_airfields (id, user_id) on delete cascade
);
create index comments_user_id_idx on public.comments (user_id);
create index comments_custom_airfield_idx on public.comments (custom_airfield_id, user_id);
create index comments_public_idx on public.comments (airfield_code) where is_public and moderation = 'visible';

-- The row comes first, then the upload: the storage policy requires a row, so quotas apply to files too.
-- Paths are generated, so a client cannot point a row at somebody else's file.
create table public.photos (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  airfield_code text check (airfield_code ~ '^[A-Z0-9-]{3,12}$'),
  custom_airfield_id uuid,
  storage_path text generated always as (user_id::text || '/' || id::text || '.jpg') stored,
  thumb_path text generated always as (user_id::text || '/' || id::text || '_thumb.jpg') stored,
  is_public boolean not null default false,
  uploaded_at timestamptz, -- set by the client once both files are stored
  moderation text not null default 'visible' check (moderation in ('visible', 'hidden')),
  client_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (num_nonnulls(airfield_code, custom_airfield_id) = 1),
  check (custom_airfield_id is null or not is_public),
  foreign key (custom_airfield_id, user_id) references public.custom_airfields (id, user_id) on delete cascade
);
create index photos_user_id_idx on public.photos (user_id);
create index photos_custom_airfield_idx on public.photos (custom_airfield_id, user_id);
create index photos_public_idx on public.photos (airfield_code) where is_public and moderation = 'visible';
create unique index photos_storage_path_key on public.photos (storage_path);
create unique index photos_thumb_path_key on public.photos (thumb_path);

-- ---------- moderation and feedback ----------

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  comment_id uuid references public.comments (id) on delete cascade,
  photo_id uuid references public.photos (id) on delete cascade,
  reason text not null check (reason in ('spam', 'offensive', 'illegal', 'privacy', 'copyright', 'other')),
  details text check (char_length(details) <= 1000),
  status text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  resolved_by uuid references auth.users (id) on delete set null,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  check (num_nonnulls(comment_id, photo_id) = 1),
  unique nulls not distinct (reporter_id, comment_id, photo_id)
);
create index reports_comment_id_idx on public.reports (comment_id);
create index reports_photo_id_idx on public.reports (photo_id);
create index reports_status_idx on public.reports (status) where status = 'open';

create table public.feedback (
  id uuid primary key default gen_random_uuid(),
  user_id uuid default auth.uid() references auth.users (id) on delete set null,
  message text not null check (char_length(message) between 1 and 2000),
  app_version text check (char_length(app_version) <= 32),
  status text not null default 'new' check (status in ('new', 'read', 'closed')),
  created_at timestamptz not null default now()
);
create index feedback_user_id_idx on public.feedback (user_id);

-- ---------- triggers ----------

create function private.set_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- Offline devices push late: a change older than the stored one is dropped, not an error.
create function private.keep_newest() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.client_updated_at < old.client_updated_at then
    return null;
  end if;
  new.updated_at := now();
  return new;
end $$;

-- Trigger arguments: owner column, max rows per owner, max rows per owner per 24 h (0 = no limit).
-- The advisory lock stops parallel requests from slipping past the count.
-- SECURITY DEFINER because reports and feedback are not readable by their authors.
create function private.enforce_limits() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  owner_id uuid := (to_jsonb(new) ->> tg_argv[0])::uuid;
  max_total int := tg_argv[1]::int;
  max_daily int := tg_argv[2]::int;
  total int;
  daily int;
begin
  if owner_id is null then
    raise exception 'owner required' using errcode = '42501';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(tg_table_name || owner_id::text, 0));
  execute format(
    'select count(*), count(*) filter (where created_at > now() - interval ''24 hours'')
       from public.%I where %I = $1', tg_table_name, tg_argv[0])
    into total, daily using owner_id;
  if (max_total > 0 and total >= max_total) or (max_daily > 0 and daily >= max_daily) then
    raise exception 'limit reached on %', tg_table_name using errcode = 'P0001';
  end if;
  return new;
end $$;

create function private.limit_photos_per_airfield() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if (select count(*) from public.photos p
      where p.user_id = new.user_id
        and p.airfield_code is not distinct from new.airfield_code
        and p.custom_airfield_id is not distinct from new.custom_airfield_id) >= 3 then
    raise exception 'limit reached: 3 photos per airfield' using errcode = 'P0001';
  end if;
  return new;
end $$;

-- A public item shows the author's nickname, so there has to be one.
create function private.require_nickname() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.is_public and not exists (select 1 from public.profiles p where p.id = new.user_id) then
    raise exception 'a nickname is required to publish' using errcode = 'P0001';
  end if;
  return new;
end $$;

